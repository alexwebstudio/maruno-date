-- ============================================================
-- Maruno — направление сайта (Wedding / Birthday / …)
--
-- Один аккаунт и одна таблица projects обслуживают все направления
-- экосистемы Maruno. Этот столбец отвечает на единственный вопрос:
-- к какому направлению относится сайт.
--
-- Миграция обратно совместима: все существующие записи получают
-- 'wedding', код, который про столбец не знает, продолжает работать.
-- Откат — DROP COLUMN.
-- ============================================================

ALTER TABLE public.projects
  ADD COLUMN IF NOT EXISTS event_type TEXT NOT NULL DEFAULT 'wedding';

-- Кабинет всегда запрашивает сайты одного пользователя в одном направлении,
-- отсортированные по дате создания — индекс повторяет этот запрос.
CREATE INDEX IF NOT EXISTS idx_projects_user_event
  ON public.projects(user_id, event_type, created_at DESC);

-- RLS не меняется: политики построены на auth.uid() = user_id
-- и продолжают действовать без правок.
