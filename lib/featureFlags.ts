/**
 * Платные тарифы.
 *
 * Включены. Тарифов два — FREE и STANDARD — и их ограничения действуют
 * по-настоящему: FREE ограничен двумя приглашениями и не добавляет
 * дополнительные сцены, STANDARD снимает эти ограничения. Оплата пока
 * «демо»: переход на STANDARD включается на странице тарифов и хранится
 * за аккаунтом (lib/subscription.ts). Когда подключат платёжку — она
 * встанет ровно на это место, ничего в лимитах менять не придётся.
 */
export const PAID_PLANS_ENABLED = true

/**
 * Сколько приглашений помещается в аккаунт.
 *
 * Замысел тарифа: 2000 ₸ за аккаунт, до десяти приглашений внутри.
 * Одно число на весь продукт — и кабинет, и мастер создания, и страница
 * тарифов читают его отсюда, поэтому разойтись они не могут.
 */
export const INVITATIONS_PER_ACCOUNT = 10

/** Сколько приглашений можно создать бесплатно, чтобы попробовать. */
export const FREE_INVITATIONS = 2

/**
 * Ограничение действует только вместе с платными тарифами: пока купить
 * «Стандарт» нельзя, лимит превратился бы в тупик — человек упёрся бы
 * в стену, которую нечем оплатить. Поэтому до подключения оплаты
 * все получают полный лимит аккаунта.
 */
export function siteLimitFor(plan: 'start' | 'standard'): number {
  if (!PAID_PLANS_ENABLED) return INVITATIONS_PER_ACCOUNT
  return plan === 'standard' ? INVITATIONS_PER_ACCOUNT : FREE_INVITATIONS
}

/** По той же причине добавление сцен открыто, пока оплата не работает. */
export function canAddBlocksNow(plan: 'start' | 'standard'): boolean {
  if (!PAID_PLANS_ENABLED) return true
  return plan === 'standard'
}
